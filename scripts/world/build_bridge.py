#!/usr/bin/env python3
"""Build the Projects bridge art: the captain's sprite atlas and the deck backdrop.

    python3 scripts/world/build_bridge.py designs dashboard

Reads (from the designs folder):
    captain-sheet.png   3 rows x 4 columns on flat magenta: idle / brief / call
    bridge-deck.png     the empty operations deck (no interface, no characters)
Writes:
    dashboard/public/world/bridge/captain.png   the keyed atlas (same grid, one shared trim box)
    dashboard/public/world/bridge/deck.jpg
    dashboard/src/world/bridge/bridge.generated.ts
Either input may be missing: what is missing is written as null and the screen does without.
"""
import sys, os
from PIL import Image
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_crew_sheets import keyed  # the same chroma key as the crew

ROWS = ['idle', 'brief', 'call']
COLS = 4
CELL_H = 320


def captain(designs, out):
    src = os.path.join(designs, 'captain-sheet.png')
    if not os.path.exists(src):
        print('captain-sheet.png not found - captain: null')
        return None
    img = keyed(src, 'magenta')
    w, h = img.size
    cw, ch = w / COLS, h / len(ROWS)
    cells = [[img.crop((round(c * cw), round(r * ch), round((c + 1) * cw), round((r + 1) * ch))) for c in range(COLS)] for r in range(len(ROWS))]
    # One trim box for every cell, so the figure does not jump between frames or cycles.
    box = None
    for row in cells:
        for cell in row:
            b = Image.fromarray((np.asarray(cell)[..., 3] > 40).astype(np.uint8) * 255).getbbox()
            if b:
                box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    pad = 6
    box = (max(0, box[0] - pad), max(0, box[1] - pad), min(round(cw), box[2] + pad), min(round(ch), box[3] + pad))
    bw, bh = box[2] - box[0], box[3] - box[1]
    fw = round(bw * CELL_H / bh)
    atlas = Image.new('RGBA', (fw * COLS, CELL_H * len(ROWS)), (0, 0, 0, 0))
    for r, row in enumerate(cells):
        for c, cell in enumerate(row):
            atlas.paste(cell.crop(box).resize((fw, CELL_H), Image.NEAREST), (c * fw, r * CELL_H))
    atlas.save(os.path.join(out, 'captain.png'), optimize=True)
    print(f'captain  {COLS}x{len(ROWS)} cells of {fw}x{CELL_H}')
    rows = ', '.join(f"{name}: {{ row: {i}, frames: {COLS} }}" for i, name in enumerate(ROWS))
    return f"{{ src: '/world/bridge/captain.png', frameW: {fw}, frameH: {CELL_H}, rows: {{ {rows} }} }}"


def deck(designs, out):
    src = os.path.join(designs, 'bridge-deck.png')
    if not os.path.exists(src):
        print('bridge-deck.png not found - deck: null')
        return None
    img = Image.open(src).convert('RGB')
    img = img.resize((img.width * 2, img.height * 2), Image.LANCZOS) if img.width < 1800 else img
    img.save(os.path.join(out, 'deck.jpg'), quality=88)
    print(f'deck     {img.size}')
    return "'/world/bridge/deck.jpg'"


def main():
    designs, dash = sys.argv[1], sys.argv[2]
    out = os.path.join(dash, 'public', 'world', 'bridge')
    os.makedirs(out, exist_ok=True)
    cap, dk = captain(designs, out), deck(designs, out)
    ts = os.path.join(dash, 'src', 'world', 'bridge', 'bridge.generated.ts')
    with open(ts, 'w') as f:
        f.write("// GENERATED by scripts/world/build_bridge.py — do not edit by hand.\n"
                "// Until the art is built, both are null: the bridge shows its panels and no figure.\n"
                "export interface CaptainSheet {\n  src: string;\n  frameW: number;\n  frameH: number;\n"
                "  rows: Record<'idle' | 'brief' | 'call', { row: number; frames: number }>;\n}\n"
                f"export const BRIDGE: {{ captain: CaptainSheet | null; deck: string | null }} = {{ captain: {cap or 'null'}, deck: {dk or 'null'} }};\n")


if __name__ == '__main__':
    main()
