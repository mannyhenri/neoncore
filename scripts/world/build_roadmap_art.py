#!/usr/bin/env python3
"""
Build the ROADMAP's drawn art (Projects → a project → Roadmap), for every theme.

Reads, from designs/ (sci-fi) and designs/<theme>/ (a theme pack), five sheets:
    roadmap-deck.png          the empty room the chart sits in
    roadmap-destination.png   1 row x 4: the vision's destination, turning
    roadmap-today.png         1 row x 4: the marker that rides the TODAY line
    roadmap-epic-icons.png    2 rows x 4: one glyph per epic
    roadmap-waypoints.png     1 row x 4: a feature's marker — planned, under way, delivered, late
Writes dashboard/public/world[/<theme>]/roadmap/ and src/world/roadmap/roadmapArt.generated.ts.
A sheet that is missing is null: the chart then draws that part plainly (a dot, no glyph).

Usage: python3 scripts/world/build_roadmap_art.py
"""
import os, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from build_world_kit import keyed

THEMES = {
    'scifi': {'designs': 'designs', 'web': '/world/roadmap', 'icons': ['planet', 'antenna', 'gear', 'compass', 'rocket', 'shield', 'flask', 'satellite']},
    'fantasy': {'designs': 'designs/fantasy', 'web': '/world/fantasy/roadmap', 'icons': ['tower', 'horn', 'anvil', 'compass', 'ship', 'shield', 'potion', 'scroll']},
}
WAYPOINTS = ['planned', 'under-way', 'delivered', 'late']


def cells(path, cols, rows):
    img = keyed(path)
    W, H = img.size
    return [img.crop((round(c * W / cols), round(r * H / rows), round((c + 1) * W / cols), round((r + 1) * H / rows))) for r in range(rows) for c in range(cols)]


def union_box(frames):
    box = None
    for f in frames:
        b = Image.fromarray((np.asarray(f)[..., 3] > 128).astype(np.uint8) * 255).getbbox()
        if b:
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    return box


def strip(src, out, height):
    """Four frames of one object → one strip, every frame trimmed to the same box."""
    if not os.path.exists(src):
        return 'null'
    frames = cells(src, 4, 1)
    box = union_box(frames)
    w, h = box[2] - box[0], box[3] - box[1]
    fw = round(w * height / h)
    sheet = Image.new('RGBA', (fw * 4, height), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        sheet.paste(f.crop(box).resize((fw, height), Image.LANCZOS), (i * fw, 0))
    sheet.save(out, optimize=True)
    return fw


def main():
    lines = [
        '// GENERATED by scripts/world/build_roadmap_art.py — do not edit by hand.',
        'export interface RoadmapStrip { src: string; frameW: number; frameH: number; frames: number }',
        'export interface RoadmapArt {',
        '  deck: string | null;',
        '  destination: RoadmapStrip | null;',
        '  today: RoadmapStrip | null;',
        '  /** One glyph per epic, in the order they are offered. */',
        '  icons: { id: string; src: string }[];',
        "  waypoints: Record<'planned' | 'under-way' | 'delivered' | 'late', string> | null;",
        '}',
        'export const ROADMAP_ART: Record<string, RoadmapArt> = {',
    ]
    for theme, cfg in THEMES.items():
        designs = os.path.join(ROOT, cfg['designs'])
        out = os.path.join(ROOT, 'dashboard', 'public', cfg['web'].lstrip('/'))
        os.makedirs(out, exist_ok=True)
        web = cfg['web']

        deck = 'null'
        src = os.path.join(designs, 'roadmap-deck.png')
        if os.path.exists(src):
            img = Image.open(src).convert('RGB')
            img.resize((img.width * 2, img.height * 2), Image.LANCZOS).save(os.path.join(out, 'deck.jpg'), quality=86)
            deck = f"'{web}/deck.jpg'"

        def strip_ts(name, height):
            fw = strip(os.path.join(designs, f'roadmap-{name}.png'), os.path.join(out, f'{name}.png'), height)
            return 'null' if fw == 'null' else f"{{ src: '{web}/{name}.png', frameW: {fw}, frameH: {height}, frames: 4 }}"

        destination = strip_ts('destination', 256)
        today = strip_ts('today', 96)

        icons = []
        src = os.path.join(designs, 'roadmap-epic-icons.png')
        if os.path.exists(src):
            for name, cell in zip(cfg['icons'], cells(src, 4, 2)):
                box = union_box([cell])
                side = max(box[2] - box[0], box[3] - box[1])
                glyph = Image.new('RGBA', (side, side), (0, 0, 0, 0))
                part = cell.crop(box)
                glyph.paste(part, ((side - part.width) // 2, (side - part.height) // 2))
                glyph.resize((96, 96), Image.LANCZOS).save(os.path.join(out, f'icon-{name}.png'), optimize=True)
                icons.append(f"{{ id: '{name}', src: '{web}/icon-{name}.png' }}")

        waypoints = 'null'
        src = os.path.join(designs, 'roadmap-waypoints.png')
        if os.path.exists(src):
            frames = cells(src, 4, 1)
            box = union_box(frames)
            for name, f in zip(WAYPOINTS, frames):
                part = f.crop(box)
                part.resize((round(part.width * 96 / part.height), 96), Image.LANCZOS).save(os.path.join(out, f'waypoint-{name}.png'), optimize=True)
            waypoints = '{ ' + ', '.join(f"'{n}': '{web}/waypoint-{n}.png'" for n in WAYPOINTS) + ' }'

        lines.append(f"  {theme}: {{ deck: {deck}, destination: {destination}, today: {today}, icons: [{', '.join(icons)}], waypoints: {waypoints} }},")
        print(theme, 'deck' if deck != 'null' else 'NO deck', destination != 'null', today != 'null', len(icons), 'icons', waypoints != 'null')
    lines += ['};', '']
    with open(os.path.join(ROOT, 'dashboard', 'src', 'world', 'roadmap', 'roadmapArt.generated.ts'), 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
