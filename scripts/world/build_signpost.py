#!/usr/bin/env python3
"""
THE SIGNPOST THAT HOLDS A NAME — cut from the drawn signpost, never redrawn.

Each pod's signpost carries its project's name on its board, and names run from "OPS" to
"LIGHTHOUSE MARKETING SITE". So the drawn board is cut into three pieces — a left end, a middle
and a right end — and the middle is stretched to the width the name needs. The post is the same
drawing with the board lifted off it.

  sci-fi   the glowing board hangs to the right of its mast, drawn at a slant: it is straightened
           first (a shear, nearest-pixel), then cut
  fantasy  the top arrow board, already square, sits across the post

In:   dashboard/public/world[/fantasy]/kit/signpost.png        (scripts/world/build_world_kit.py)
Out:  dashboard/public/world[/fantasy]/signpost/{post,left,mid,right}.png
      dashboard/src/world/signpost.generated.ts

Run:  python3 scripts/world/build_signpost.py
"""
import os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PUBLIC = os.path.join(ROOT, 'dashboard', 'public')

# Read off each drawing, in its own pixels.
#   quad    the board's four corners (top-left, top-right, bottom-right, bottom-left)
#   box     the board once straightened: left, top, right, bottom
#   caps    width of the left and right end pieces
#   mid     the clean stretch of board the middle piece is taken from (left, right)
#   post    the columns kept for the post (left, right)
#   mode    hang = the board hangs to the right of the mast from `attach`; center = it sits across the post
#   ink     the colour a name is written in on that board
THEMES = {
    'scifi': dict(dir='world', quad=[(76, 56), (207, 28), (213, 102), (80, 130)], slope=-0.212, pivot=76,
                  box=(74, 52, 214, 132), caps=(26, 24), mid=(118, 170), post=(0, 126), mode='hang', attach=74, ink='#3B1A00'),
    'fantasy': dict(dir='world/fantasy', quad=[(44, 40), (222, 40), (222, 104), (44, 104)], slope=0.0, pivot=0,
                    box=(44, 40, 222, 104), caps=(22, 44), mid=(124, 172), post=(0, 222), mode='center', attach=0, ink='#3A2208'),
}


def build(theme, t):
    kit = os.path.join(PUBLIC, t['dir'], 'kit')
    src = Image.open(os.path.join(kit, 'signpost.png')).convert('RGBA')
    dest = os.path.join(PUBLIC, t['dir'], 'signpost')
    os.makedirs(dest, exist_ok=True)

    # The board alone: everything outside its four corners is cleared, then it is straightened.
    mask = Image.new('L', src.size, 0)
    ImageDraw.Draw(mask).polygon(t['quad'], fill=255)
    board = Image.new('RGBA', src.size, (0, 0, 0, 0))
    board.paste(src, (0, 0), mask)
    if t['slope']:
        s, x0 = t['slope'], t['pivot']
        # Output (x, y) reads the drawing at (x, y + s·(x − x0)): each column slides up or down, whole pixels.
        board = board.transform(src.size, Image.AFFINE, (1, 0, 0, s, 1, -s * x0), resample=Image.NEAREST)
    l, top, r, bottom = t['box']
    board = board.crop((l, top, r, bottom))
    bbox = board.getbbox()
    board = board.crop((0, bbox[1], board.width, bbox[3]))
    top += bbox[1]
    cl, cr = t['caps']
    pieces = {
        'left': board.crop((0, 0, cl, board.height)),
        'mid': board.crop((t['mid'][0] - l, 0, t['mid'][1] - l, board.height)),
        'right': board.crop((board.width - cr, 0, board.width, board.height)),
    }

    # The post: the drawing with the board lifted off.
    post = src.copy()
    hole = Image.new('L', src.size, 255)
    # A few pixels wider than the cut, so no sliver of the board's outline or shadow stays on the post.
    cx = sum(x for x, _ in t['quad']) / 4
    cy = sum(y for _, y in t['quad']) / 4
    grown = [(x + (5 if x > cx else -5), y + (6 if y > cy else -6)) for x, y in t['quad']]
    ImageDraw.Draw(hole).polygon(grown, fill=0)
    post.putalpha(Image.composite(post.getchannel('A'), Image.new('L', src.size, 0), hole))
    post = post.crop((t['post'][0], 0, t['post'][1], src.height))
    pieces['post'] = post

    out = {}
    for name, im in pieces.items():
        im.save(os.path.join(dest, f'{name}.png'))
        out[name] = (f"/{t['dir']}/signpost/{name}.png", im.width, im.height)
    return dict(pieces=out, boardY=top, boardH=board.height, mode=t['mode'], attach=t['attach'] - t['post'][0], ink=t['ink'])


def main():
    lines = [
        '// GENERATED by scripts/world/build_signpost.py — do not edit.',
        "// The drawn signpost, cut so its board can hold a project's name: a post, and a board in three",
        '// pieces whose middle stretches. Sizes are in the drawing\'s own pixels.',
        'export interface SignPiece { src: string; w: number; h: number }',
        'export interface SignpostArt {',
        '  post: SignPiece; left: SignPiece; mid: SignPiece; right: SignPiece;',
        '  /** Where the board\'s top is on the post, and how tall the board is. */',
        '  boardY: number; boardH: number;',
        '  /** hang: the board hangs to the right of the mast, from `attach`. center: it sits across the post. */',
        "  mode: 'hang' | 'center'; attach: number;",
        '  /** The colour a name is written in on this board. */',
        '  ink: string;',
        '}',
        'export const SIGNPOST: Record<string, SignpostArt> = {',
    ]
    for theme, t in THEMES.items():
        b = build(theme, t)
        piece = lambda n: "{ src: '%s', w: %d, h: %d }" % b['pieces'][n]
        lines.append(f"  {theme}: {{ post: {piece('post')}, left: {piece('left')}, mid: {piece('mid')}, right: {piece('right')}, boardY: {b['boardY']}, boardH: {b['boardH']}, mode: '{b['mode']}', attach: {b['attach']}, ink: '{b['ink']}' }},")
        print(theme, b)
    lines += ['};', '']
    with open(os.path.join(ROOT, 'dashboard', 'src', 'world', 'signpost.generated.ts'), 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
