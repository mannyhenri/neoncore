#!/usr/bin/env python3
"""
Give the iOS app the same drawn art as the dashboard — nothing is redrawn for the phone.

Reads what the dashboard already serves (dashboard/public/world/, built by build_world_kit.py,
build_crew_sheets.py and build_bridge.py from the sheets in designs/) and writes:

  mobile/assets/world/terrain.jpg            the map
  mobile/assets/world/crew/<character>.png   the crew atlases
  mobile/assets/world/decks/<figure>.png     captain, engineer, quartermaster, core
  mobile/assets/world/kit/<sprite>.png       every scenery sprite
  mobile/src/world/art.generated.ts          the registry the app reads: a require() per image
                                             (metro bundles only what is required) and the frame
                                             sizes, rows and frame counts of every sheet

Everything is halved (the terrain to PHONE_TERRAIN_W): a phone draws a figure at a third of the
size the dashboard does, and a full-size atlas costs four times the memory for nothing.

Run it after any of the three build scripts:  python3 scripts/world/sync_mobile_art.py
"""
import os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WEB = os.path.join(ROOT, 'dashboard', 'public', 'world')
SRC = os.path.join(ROOT, 'dashboard', 'src', 'world')
OUT = os.path.join(ROOT, 'mobile', 'assets', 'world')
GEN = os.path.join(ROOT, 'mobile', 'src', 'world', 'art.generated.ts')
SCALE = 0.5
PHONE_TERRAIN_W = 2048


def half(src, dst):
    im = Image.open(src)
    w, h = max(1, round(im.width * SCALE)), max(1, round(im.height * SCALE))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    im.resize((w, h), Image.LANCZOS).save(dst, optimize=True)
    return w, h


def ident(name):
    return re.sub(r'[^A-Za-z0-9]', '_', name)


def main():
    lines = [
        '// GENERATED by scripts/world/sync_mobile_art.py — do not edit by hand.',
        "// The dashboard's drawn art, halved for the phone. Sizes are of the files in mobile/assets/world/.",
        '/* eslint-disable */',
        'export interface SheetArt { source: number; frameW: number; frameH: number; cols: number; rowCount: number; rows: Record<string, { row: number; frames: number }> }',
        'export interface SpriteArt { source: number; w: number; h: number }',
        '',
    ]

    # terrain
    t = Image.open(os.path.join(WEB, 'terrain.jpg')).convert('RGB')
    th = round(t.height * PHONE_TERRAIN_W / t.width)
    os.makedirs(OUT, exist_ok=True)
    t.resize((PHONE_TERRAIN_W, th), Image.LANCZOS).save(os.path.join(OUT, 'terrain.jpg'), quality=84, optimize=True)
    lines += [f"export const TERRAIN: SpriteArt = {{ source: require('../../assets/world/terrain.jpg'), w: {PHONE_TERRAIN_W}, h: {th} }};", '']

    # crew atlases — rows and cell size from the dashboard's own registry
    atlas = open(os.path.join(SRC, 'crewAtlas.generated.ts')).read()
    cell = int(re.search(r'cell: (\d+)', atlas).group(1))
    frames = int(re.search(r'frames: (\d+)', atlas).group(1))
    rows = re.findall(r"'([a-z]+)'", re.search(r'rows: \[(.*?)\]', atlas).group(1))
    lines.append('export const CREW_ART: Record<string, SheetArt & { tops: Record<string, number> }> = {')
    for name, tops in re.findall(r"(\w+): \{ src: '/world/crew/\w+\.png', tops: \{ (.*?) \} \}", atlas):
        w, h = half(os.path.join(WEB, 'crew', f'{name}.png'), os.path.join(OUT, 'crew', f'{name}.png'))
        fw = round(cell * SCALE)
        assert w == fw * frames and h == fw * len(rows), (name, w, h)
        row_map = ', '.join(f'{r}: {{ row: {i}, frames: {frames} }}' for i, r in enumerate(rows))
        lines.append(f"  {name}: {{ source: require('../../assets/world/crew/{name}.png'), frameW: {fw}, frameH: {fw}, cols: {frames}, rowCount: {len(rows)}, rows: {{ {row_map} }}, tops: {{ {tops} }} }},")
    lines += ['};', '']

    # deck figures
    bridge = open(os.path.join(SRC, 'bridge', 'bridge.generated.ts')).read()
    lines.append('export const DECK_ART: Record<string, SheetArt> = {')
    for name, fw, fh, rowsrc in re.findall(r"(\w+): \{ src: '/world/bridge/\w+\.png', frameW: (\d+), frameH: (\d+), rows: \{ (.*?\}) \} \}", bridge):
        src = os.path.join(WEB, 'bridge', f'{name}.png')
        full = Image.open(src)
        cols, count = round(full.width / int(fw)), round(full.height / int(fh))
        w, h = half(src, os.path.join(OUT, 'decks', f'{name}.png'))
        # From the halved FILE, so a sheet whose frame is an odd number of pixels wide still steps exactly.
        lines.append(f"  {name}: {{ source: require('../../assets/world/decks/{name}.png'), frameW: {w / cols:g}, frameH: {h / count:g}, cols: {cols}, rowCount: {count}, rows: {{ {rowsrc} }} }},")
    lines += ['};', '']

    # scenery kit
    kit = open(os.path.join(SRC, 'kit.generated.ts')).read()
    lines.append('export const KIT_ART: Record<string, SpriteArt> = {')
    for name in re.findall(r"'([a-z0-9-]+)': \{ src: '/world/kit/", kit):
        w, h = half(os.path.join(WEB, 'kit', f'{name}.png'), os.path.join(OUT, 'kit', f'{name}.png'))
        lines.append(f"  '{name}': {{ source: require('../../assets/world/kit/{name}.png'), w: {w}, h: {h} }},")
    lines += ['};', '']

    os.makedirs(os.path.dirname(GEN), exist_ok=True)
    with open(GEN, 'w') as f:
        f.write('\n'.join(lines))
    total = sum(os.path.getsize(os.path.join(d, x)) for d, _, fs in os.walk(OUT) for x in fs)
    print(f'mobile art: {total / 1e6:.1f} MB in {OUT}')


if __name__ == '__main__':
    sys.exit(main())
